#!/usr/bin/env python3
"""Generates vcu128_hbm.sv: the Xilinx HBM IP (hbm_0, both stacks, all 32 AXI ports) with its
AXI ports as arrays, h_*[i] = AXI_i. Which channel uses which port is otpu_vcu128_top's choice.

    python3 vcu128_otpu/src/hbm/gen_vcu128_hbm.py > vcu128_otpu/src/hbm/vcu128_hbm.sv
"""
import sys

NHP = 32
HEAD = f"""// GENERATED by gen_vcu128_hbm.py -- do not edit.
// Xilinx HBM IP (hbm_0, both stacks, 8 GB) with all {NHP} AXI ports as arrays: h_*[i] = AXI_i
// (port i sits in mini-switch i / 4, next to pseudo-channels 4 (i / 4) .. 4 (i / 4) + 3).
// Which channel drives which port is otpu_vcu128_top's (doc/design.md, src/hbm/README.md
// «Порты HBM IP»); ports it does not use it ties off. All AXI ports on aclk (uclk, 225 MHz =
// the IP's AXI_CLK_FREQ).
module vcu128_hbm #(
    localparam int NHP = {NHP}
) (
    input  wire                   hbm_ref,     // HBM_REF_CLK_0/1 (100 MHz)
    input  wire                   aclk,
    input  wire                   aresetn,
    input  wire                   pclk,        // APB (100 MHz = USER_APB_PCLK)
    input  wire                   presetn,
"""
PORTS = [("input ", "[32:0]  ", "awaddr"), ("input ", "[1:0]   ", "awburst"), ("input ", "[5:0]   ", "awid"),
         ("input ", "[3:0]   ", "awlen"), ("input ", "[2:0]   ", "awsize"), ("input ", "        ", "awvalid"),
         ("output", "        ", "awready"), ("input ", "[255:0] ", "wdata"), ("input ", "        ", "wlast"),
         ("input ", "[31:0]  ", "wstrb"), ("input ", "[31:0]  ", "wpar"), ("input ", "        ", "wvalid"),
         ("output", "        ", "wready"), ("input ", "        ", "bready"), ("output", "[5:0]   ", "bid"),
         ("output", "[1:0]   ", "bresp"), ("output", "        ", "bvalid"), ("input ", "[32:0]  ", "araddr"),
         ("input ", "[1:0]   ", "arburst"), ("input ", "[5:0]   ", "arid"), ("input ", "[3:0]   ", "arlen"),
         ("input ", "[2:0]   ", "arsize"), ("input ", "        ", "arvalid"), ("output", "        ", "arready"),
         ("input ", "        ", "rready"), ("output", "[255:0] ", "rdata"), ("output", "[5:0]   ", "rid"),
         ("output", "        ", "rlast"), ("output", "[1:0]   ", "rresp"), ("output", "        ", "rvalid")]


def port(i):
    n = f"{i:02d}"
    return f"""        // h_*[{i}]: AXI_{n}
        .AXI_{n}_ACLK         (aclk), .AXI_{n}_ARESET_N (aresetn),
        .AXI_{n}_ARADDR       (h_araddr[{i}]), .AXI_{n}_ARBURST (h_arburst[{i}]), .AXI_{n}_ARID (h_arid[{i}]),
        .AXI_{n}_ARLEN        (h_arlen[{i}]),  .AXI_{n}_ARSIZE  (h_arsize[{i}]),  .AXI_{n}_ARVALID (h_arvalid[{i}]),
        .AXI_{n}_ARREADY      (h_arready[{i}]),
        .AXI_{n}_AWADDR       (h_awaddr[{i}]), .AXI_{n}_AWBURST (h_awburst[{i}]), .AXI_{n}_AWID (h_awid[{i}]),
        .AXI_{n}_AWLEN        (h_awlen[{i}]),  .AXI_{n}_AWSIZE  (h_awsize[{i}]),  .AXI_{n}_AWVALID (h_awvalid[{i}]),
        .AXI_{n}_AWREADY      (h_awready[{i}]),
        .AXI_{n}_WDATA        (h_wdata[{i}]),  .AXI_{n}_WLAST   (h_wlast[{i}]),   .AXI_{n}_WSTRB (h_wstrb[{i}]),
        .AXI_{n}_WDATA_PARITY (h_wpar[{i}]),   .AXI_{n}_WVALID  (h_wvalid[{i}]),  .AXI_{n}_WREADY (h_wready[{i}]),
        .AXI_{n}_RREADY       (h_rready[{i}]), .AXI_{n}_RDATA   (h_rdata[{i}]),   .AXI_{n}_RDATA_PARITY (),
        .AXI_{n}_RID          (h_rid[{i}]),    .AXI_{n}_RLAST   (h_rlast[{i}]),   .AXI_{n}_RRESP (h_rresp[{i}]),
        .AXI_{n}_RVALID       (h_rvalid[{i}]),
        .AXI_{n}_BREADY       (h_bready[{i}]), .AXI_{n}_BID     (h_bid[{i}]),     .AXI_{n}_BRESP (h_bresp[{i}]),
        .AXI_{n}_BVALID       (h_bvalid[{i}]),
"""


TAIL = """        .APB_0_PCLK          (pclk), .APB_0_PRESET_N (presetn),
        .APB_0_PWDATA        (32'd0), .APB_0_PADDR (22'd0), .APB_0_PENABLE (1'b0),
        .APB_0_PSEL          (1'b0),  .APB_0_PWRITE (1'b0),
        .APB_0_PRDATA        (), .APB_0_PREADY (), .APB_0_PSLVERR (),
        .APB_1_PCLK          (pclk), .APB_1_PRESET_N (presetn),
        .APB_1_PWDATA        (32'd0), .APB_1_PADDR (22'd0), .APB_1_PENABLE (1'b0),
        .APB_1_PSEL          (1'b0),  .APB_1_PWRITE (1'b0),
        .APB_1_PRDATA        (), .APB_1_PREADY (), .APB_1_PSLVERR (),
        .apb_complete_0      (calib[0]),
        .apb_complete_1      (calib[1]),
        .DRAM_0_STAT_CATTRIP (cattrip[0]),
        .DRAM_0_STAT_TEMP    (temp0),
        .DRAM_1_STAT_CATTRIP (cattrip[1]),
        .DRAM_1_STAT_TEMP    (temp1)
    );
endmodule
"""

out = [HEAD]
for d, w, n in PORTS:
    out.append(f"    {d} wire [NHP-1:0]{w}h_{n},\n".replace("[NHP-1:0]        ", "[NHP-1:0]         "))
out.append("""    output wire [1:0]             calib,       // apb_complete_0/1
    output wire [1:0]             cattrip,
    output wire [6:0]             temp0,
    output wire [6:0]             temp1
);
    hbm_0 u_hbm (
        .HBM_REF_CLK_0       (hbm_ref),
        .HBM_REF_CLK_1       (hbm_ref),
""")
out += [port(i) for i in range(NHP)]
out.append(TAIL)
sys.stdout.write("".join(out))
